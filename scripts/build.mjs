import { readFile, mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const source = await readFile(new URL('src/client.js', root), 'utf8');
const names = [...source.matchAll(/export (?:function|const) (\w+)/g)].map(m => m[1]);
const bundle = `// Generated by scripts/build.mjs; edit src/client.js.\nwindow.__ModuleLoader__.load({id:'dsh-nextline',factory:(require)=>{\n${source.replace(/export (?=function|const)/g, '')}\nreturn {${names.join(',')}};\n}});\n`;
await mkdir(new URL('lib/', root), { recursive: true });
await writeFile(new URL('lib/client.js', root), bundle);
console.log('Built lib/client.js (no bundler dependencies).');
